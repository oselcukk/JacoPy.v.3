class CourantLocalityDefinition(Definition):
    """``ᵍL(Ω, u, v) → g(u,v)·g⁻¹(Ω)`` [MC Prop 4.1]: on an
    almost-Courant algebroid the locality operator is generated by
    the E-metric. Expansion direction (metric/sharp outputs never
    re-create an ``L`` node)."""

    anchor = LocalityOperator

    def __init__(self, alg: Algebroid) -> None:
        if alg.is_tangent:
            raise ValueError(
                "the tangent algebroid carries no E-metric/locality "
                "layer"
            )
        self._alg = alg
        self.name = (
            f"Courant locality ({alg.name}): "
            "L(Ω,u,v) = g(u,v)·g⁻¹(Ω)"
        )

    def matches(self, expr: Expr) -> bool:
        return (
            isinstance(expr, LocalityOperator)
            and expr.algebroid_name == self._alg.name
        )

    def rewrite(self, expr: Expr) -> Expr:
        form, u, v = expr.rewritable_slots
        return Product(
            self._alg.metric(u, v), self._alg.sharp(form)
        )


class MetricCompatibilityCollection(Definition):
    """Declared metric compatibility ``Q(∇, g) = 0`` in the
    COLLECTION direction, across a framed pair of indexed sums:

        Σ_s c(s)·g(∇_{e_s}a, b) + Σ_s c(s)·g(∇_{e_s}b, a)
            → Σ_s c(s)·ρ(e_s)(g(a,b))

    (with a common body cofactor tuple ``c(s)``, e.g. ``g⁻¹(e^s)``).
    A swap orientation would cycle against the coboundary pairing —
    same design decision as the C2/admissibility collections. The
    output body is a Product of bound factors, so the indexed-sum
    linearity split cannot undo it (no ping-pong)."""

    anchor = Sum

    def __init__(self, alg: Algebroid, conn: Connection) -> None:
        self._alg = alg
        self._conn = conn
        self.name = (
            f"declared metric compatibility ({alg.name}, "
            f"{conn.name}): g(∇_x a, b) + g(a, ∇_x b) = ρ(x)(g(a,b))"
        )

    def _metric_body(self, term: Expr):
        """``(sign, dummy, range, cofactors, x, cov_arg, plain)`` for
        a term carrying exactly one E-metric factor with one
        ``∇_x``-applied slot — either inside an IndexedSum over a
        frame direction (``dummy`` = the bound name) or as a PLAIN
        summand with an arbitrary direction (``dummy = range =
        None``)."""
        from jacopy.central.algebroid.context import EMetric
        from jacopy.central.objects.connection import CovariantOp
        from jacopy.central.objects.frame import FrameField

        sign = 1
        core = term
        if isinstance(core, Neg):
            sign = -1
            core = core.arg
        if isinstance(core, IndexedSum):
            dummy = core.dummy._repr_inner()
            range_ = core.range_
            body = core.body
        else:
            dummy = None
            range_ = None
            body = core
        factors = (
            list(body.children)
            if isinstance(body, Product)
            else [body]
        )
        metrics = [
            (k, c)
            for k, c in enumerate(factors)
            if isinstance(c, EMetric)
            and c.algebroid_name == self._alg.name
        ]
        if len(metrics) != 1:
            return None
        k, m = metrics[0]
        cofactors = tuple(
            c for j, c in enumerate(factors) if j != k
        )

        def _cov_split(slot_a: Expr, slot_b: Expr):
            if not (
                isinstance(slot_a, Act)
                and isinstance(slot_a.op, CovariantOp)
                and slot_a.op.connection_name == self._conn.name
            ):
                return None
            direction = slot_a.op.vector
            if dummy is not None and not (
                isinstance(direction, FrameField)
                and direction.index == dummy
            ):
                return None
            return direction, slot_a.arg, slot_b

        split = _cov_split(m.u, m.v) or _cov_split(m.v, m.u)
        if split is None:
            return None
        x, cov_arg, plain = split
        return sign, dummy, range_, cofactors, x, cov_arg, plain

    @staticmethod
    def _cofactor_key(cofactors):
        return tuple(sorted(c._repr_inner() for c in cofactors))

    def _find_pair(self, expr: Sum):
        terms = expr.children
        for i, ti in enumerate(terms):
            si = self._metric_body(ti)
            if si is None:
                continue
            for j in range(i + 1, len(terms)):
                sj = self._metric_body(terms[j])
                if sj is None:
                    continue
                if (
                    si[0] == sj[0]
                    and si[1] == sj[1]
                    and si[2] == sj[2]
                    and si[4] == sj[4]
                    and self._cofactor_key(si[3])
                    == self._cofactor_key(sj[3])
                    and si[5] == sj[6]
                    and si[6] == sj[5]
                ):
                    return (i, j), si
        return None

    def matches(self, expr: Expr) -> bool:
        return isinstance(expr, Sum) and self._find_pair(expr) is not None

    def rewrite(self, expr: Expr) -> Expr:
        (i, j), (sign, dummy, fr, cofactors, x, a, b) = (
            self._find_pair(expr)
        )
        from jacopy.central.objects.frame import FrameIndex

        if a._repr_inner() > b._repr_inner():
            a, b = b, a
        body: Expr = Act(
            self._alg.anchor(x), self._alg.metric(a, b)
        )
        if cofactors:
            body = Product(body, *cofactors)
        collected: Expr = (
            body
            if dummy is None
            else IndexedSum(FrameIndex(dummy), fr, body)
        )
        if sign < 0:
            collected = Neg(collected)
        rest = [
            t for k, t in enumerate(expr.children) if k not in (i, j)
        ]
        if not rest:
            return collected
        return Sum(*rest, collected)


