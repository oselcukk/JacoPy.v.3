def prove_torsion_free_implies_admissible(
    alg: Algebroid,
    conn: Connection,
    fr: Frame,
    u: Expr,
    v: Expr,
    *,
    registry: Optional[PropertyRegistry] = None,
) -> ProofChain:
    """[ADM Prop 3.3]: under the declared ``ᴸT(∇) = 0`` the
    admissibility equation
    ``[u,v] + [v,u] = ΣL(e^s,∇u,v) + ΣL(e^s,∇v,u)`` closes
    mechanically (the ``∇`` terms cancel pairwise)."""
    engine = _engine(alg, fr, registry)
    engine.register(
        ModifiedTorsionFreeDeclaration(alg, conn, fr)
    )
    lhs = Sum(alg.bracket(u, v), alg.bracket(v, u))
    rhs = Sum(
        _locality_sum(alg, conn, fr, u, v, "s"),
        _locality_sum(alg, conn, fr, v, u, "s"),
    )
    return ExpandAndSimplify().prove(
        lhs, rhs, registry=registry, engine=engine
    )


def prove_modified_torsion_symmetric_part_vanishes(
    alg: Algebroid,
    conn: Connection,
    fr: Frame,
    u: Expr,
    v: Expr,
    *,
    registry: Optional[PropertyRegistry] = None,
) -> ProofChain:
    """[ADM Cor 3.2] in symmetric-part form:
    ``ᴸT(u,v) + ᴸT(v,u) = 0`` for an ADMISSIBLE connection (the
    declaration collects the transposed bracket pair). Honest fail
    without the declaration (tested)."""
    engine = _engine(alg, fr, registry)
    engine.register(AdmissibilityDeclaration(alg, conn, fr))
    lhs = Sum(
        modified_torsion(alg, conn, fr, u, v),
        modified_torsion(alg, conn, fr, v, u),
    )
    from jacopy.core.expr import Integer

    return ExpandAndSimplify().prove(
        lhs, Integer(0), registry=registry, engine=engine
    )


def prove_courant_locality_generator(
    alg: Algebroid,
    fr: Frame,
    u: Expr,
    v: Expr,
    f: Expr,
    *,
    registry: Optional[PropertyRegistry] = None,
) -> ProofChain:
    """[MC Prop 4.1 / Bourbaki eq (4.8)]: the almost-Courant
    symmetric part ``S(u,v) := g⁻¹(D g(u,v))`` satisfies the local
    consistency condition with the metric-generated locality
    operator:

        S(f·u, v) = f·S(u, v) + ᵍL(Df, u, v).

    Mechanism: metric bilinearity + coboundary Leibniz + sharp
    linearity + the ᵍL rule."""
    from jacopy.central.algebroid.rules import (
        CoboundaryLinearityDefinition,
    )

    engine = _engine(alg, fr, registry)
    engine.register(CourantLocalityDefinition(alg))
    engine.register(CoboundaryLinearityDefinition(alg, registry))
    lhs = alg.sharp(alg.D(alg.metric(Product(f, u), v)))
    rhs = Sum(
        Product(f, alg.sharp(alg.D(alg.metric(u, v)))),
        LocalityOperator(alg.name, alg.D(f), u, v),
    )
    return ExpandAndSimplify().prove(
        lhs, rhs, registry=registry, engine=engine
    )


def prove_metric_compatible_implies_admissible(
    alg: Algebroid,
    conn: Connection,
    fr: Frame,
    u: Expr,
    v: Expr,
    *,
    registry: Optional[PropertyRegistry] = None,
) -> ProofChain:
    """[ADM Prop 3.5, ⟸ direction]: on an almost-Courant algebroid
    (locality = ᵍL), a METRIC-COMPATIBLE connection satisfies the
    admissibility equation:

        Σ_s ᵍL(e^s, ∇_{e_s}u, v) + Σ_s ᵍL(e^s, ∇_{e_s}v, u)
            = g⁻¹(D g(u,v))   (the C2 symmetric part).

    Mechanism: ᵍL rule → framed compatibility collection → coframe
    recombination (with ``E = g⁻¹``). The ⟹ direction needs the
    non-degeneracy stripping tactic — 4.F.2b. Honest fail without
    the compatibility declaration (tested)."""
    engine = _engine(alg, fr, registry)
    engine.register(CourantLocalityDefinition(alg))
    engine.register(MetricCompatibilityCollection(alg, conn))
    lhs = Sum(
        _locality_sum(alg, conn, fr, u, v, "s"),
        _locality_sum(alg, conn, fr, v, u, "s"),
    )
    rhs = alg.sharp(alg.D(alg.metric(u, v)))
    return ExpandAndSimplify().prove(
        lhs, rhs, registry=registry, engine=engine
    )


def prove_admissible_implies_metric_compatible(
    alg: Algebroid,
    conn: Connection,
    fr: Frame,
    u: Expr,
    v: Expr,
    *,
    direction: str = "a",
    registry: Optional[PropertyRegistry] = None,
) -> ProofChain:
    """[ADM Prop 3.5, ⟹ direction — completes the equivalence]: on
    an almost-Courant algebroid, an ADMISSIBLE connection is
    metric-compatible on the frame directions:

        ρ(e_a)(g(u,v)) = g(∇_{e_a}u, v) + g(u, ∇_{e_a}v).

    Two-leg tactic (the 3.D pattern): the bracket's symmetric part
    ``S = [u,v] + [v,u]`` is expanded once through the C2
    symmetric-part axiom (→ ``g⁻¹Dg``) and once through the
    admissibility declaration (→ ``ΣᵍL``); the two results are
    combined and paired with the frame direction ``e_a`` — both
    pairings evaluate mechanically (sharp evaluation + coboundary
    pairing on the left; ᵍL + frame duality + Kronecker contraction
    on the right). The combine and congruence steps are explicitly
    labeled synthetic inferences."""
    from jacopy.central.tangent.definitions import (
        FrameDualityDefinition,
    )

    e_dir = fr.field(direction)
    S = Sum(alg.bracket(u, v), alg.bracket(v, u))
    c2_form = alg.sharp(alg.D(alg.metric(u, v)))
    adm_form = Sum(
        _locality_sum(alg, conn, fr, u, v, "s"),
        _locality_sum(alg, conn, fr, v, u, "s"),
    )

    eng1 = _engine(alg, fr, registry)
    eng1.register(SymmetricPartDeclaration(alg))
    leg1 = ExpandAndSimplify().prove(
        S, c2_form, registry=registry, engine=eng1
    )
    step1 = ProofStep(
        S,
        c2_form,
        rule="symmetric part (C2, almost-Courant axiom)",
        justification="[u,v] + [v,u] = g⁻¹(D g(u,v))",
    )
    for s in leg1:
        step1.add_child(s)

    eng2 = _engine(alg, fr, registry)
    eng2.register(AdmissibilityDeclaration(alg, conn, fr))
    leg2 = ExpandAndSimplify().prove(
        S, adm_form, registry=registry, engine=eng2
    )
    step2 = ProofStep(
        S,
        adm_form,
        rule="declared admissibility",
        justification="[u,v] + [v,u] = ΣᵍL(e^s,∇u,v) + ΣᵍL(e^s,∇v,u)",
    )
    for s in leg2:
        step2.add_child(s)

    step3 = ProofStep(
        c2_form,
        adm_form,
        rule="combine the two legs",
        justification=(
            "both equal the symmetric part [u,v] + [v,u]"
        ),
    )
    lhs_paired = alg.metric(c2_form, e_dir)
    rhs_paired = alg.metric(adm_form, e_dir)
    step4 = ProofStep(
        lhs_paired,
        rhs_paired,
        rule="congruence: apply g(·, e_a) to both sides",
        justification="g is a well-defined map on sections",
    )

    eng3 = _engine(alg, fr, registry)
    target_lhs = Act(alg.anchor(e_dir), alg.metric(u, v))
    leg3 = ExpandAndSimplify().prove(
        lhs_paired, target_lhs, registry=registry, engine=eng3
    )
    step5 = ProofStep(
        lhs_paired,
        target_lhs,
        rule="evaluate the C2 side",
        justification="sharp evaluation + coboundary pairing",
    )
    for s in leg3:
        step5.add_child(s)

    eng4 = _engine(alg, fr, registry)
    eng4.register(CourantLocalityDefinition(alg))
    eng4.register(FrameDualityDefinition())
    target_rhs = Sum(
        alg.metric(conn(e_dir, u), v),
        alg.metric(conn(e_dir, v), u),
    )
    leg4 = ExpandAndSimplify().prove(
        rhs_paired, target_rhs, registry=registry, engine=eng4
    )
    step6 = ProofStep(
        rhs_paired,
        target_rhs,
        rule="evaluate the admissibility side",
        justification=(
            "ᵍL + frame duality + Kronecker contraction"
        ),
    )
    for s in leg4:
        step6.add_child(s)

    step7 = ProofStep(
        target_lhs,
        target_rhs,
        rule="metric compatibility on the frame direction",
        justification=(
            "chain the evaluated sides: ρ(e_a)(g(u,v)) = "
            "g(∇_{e_a}u,v) + g(u,∇_{e_a}v)"
        ),
    )
    return ProofChain(
        [step1, step2, step3, step4, step5, step6, step7]
    )


def prove_modified_bracket_left_leibniz(
    alg: Algebroid,
    conn: Connection,
    fr: Frame,
    u: Expr,
    v: Expr,
    f: Expr,
    *,
    registry: Optional[PropertyRegistry] = None,
) -> ProofChain:
    """[ADM Prop 3.2, dull part]: for ANY linear E-connection,

        [f·u, v]^∇ = f·[u,v]^∇ − ρ(v)(f)·u

    — the locality defect of the left-Leibniz rule is cancelled by
    the recombined correction, so the modified pair
    ``(E, ρ, [·,·]^∇, L=0)`` is almost-dull. No declaration."""
    lhs = modified_bracket(alg, conn, fr, Product(f, u), v)
    rhs = Sum(
        Product(f, modified_bracket(alg, conn, fr, u, v)),
        Neg(Product(Act(alg.anchor(v), f), u)),
    )
    return ExpandAndSimplify().prove(
        lhs,
        rhs,
        registry=registry,
        engine=_engine(alg, fr, registry),
    )
