def _locality_sum(
    alg: Algebroid,
    conn: Connection,
    fr: Frame,
    u: Expr,
    v: Expr,
    bound: str,
) -> Expr:
    """``Σ_s L(e^s, ∇_{e_s}u, v)`` — the admissibility generator."""
    return IndexedSum(
        FrameIndex(bound),
        fr,
        LocalityOperator(
            alg.name,
            fr.dual().field(bound),
            conn(fr.field(bound), u),
            v,
        ),
    )


def modified_bracket(
    alg: Algebroid,
    conn: Connection,
    fr: Frame,
    u: Expr,
    v: Expr,
    *,
    bound: str = "s",
) -> Expr:
    """``[u,v]^∇ := [u,v]_E − Σ_s L(e^s, ∇_{e_s}u, v)``
    [ADM eq (3.12) with the canonical representative]."""
    if fr.bundle != alg.bundle:
        raise ValueError(
            "the frame must live on the algebroid's bundle"
        )
    return Sum(
        alg.bracket(u, v),
        Neg(_locality_sum(alg, conn, fr, u, v, bound)),
    )


class AdmissibilityDeclaration(SymmetricPartDeclaration):
    """The admissibility axiom [ADM Def 3.4], applied in the
    COLLECTION direction: a same-signed transposed bracket pair
    ``±(c·[a,b] … c·[b,a])`` inside a sum is replaced by
    ``±c·(Σ_s L(e^s,∇_{e_s}a,b) + Σ_s L(e^s,∇_{e_s}b,a))``, and the
    equal-slot summand ``c·[u,u]`` by half of it. Collection shapes
    and cycle-avoidance rationale inherited from the C2
    :class:`SymmetricPartDeclaration`."""

    def __init__(
        self,
        alg: Algebroid,
        conn: Connection,
        fr: Frame,
        *,
        bound: str = "s",
    ) -> None:
        super().__init__(alg)
        if fr.bundle != alg.bundle:
            raise ValueError(
                "the frame must live on the algebroid's bundle"
            )
        self._conn = conn
        self._fr = fr
        self._bound = bound
        self.name = (
            f"admissible connection ({alg.name}, {conn.name}): "
            "[u,v] + [v,u] = ΣL(e^s,∇u,v) + ΣL(e^s,∇v,u)"
        )

    def rewrite(self, expr: Expr) -> Expr:
        indices, sign, cofactors, br, half = self._find_collection(
            expr
        )
        a, b = br.u, br.v
        if a._repr_inner() > b._repr_inner():
            a, b = b, a
        correction: Expr = Sum(
            _locality_sum(
                self._alg, self._conn, self._fr, a, b, self._bound
            ),
            _locality_sum(
                self._alg, self._conn, self._fr, b, a, self._bound
            ),
        )
        factors = ((Rational(1, 2),) if half else ()) + tuple(
            cofactors
        )
        if factors:
            correction = Product(*factors, correction)
        if sign < 0:
            correction = Neg(correction)
        rest = [
            t
            for k, t in enumerate(expr.children)
            if k not in indices
        ]
        if not rest:
            return correction
        return Sum(*rest, correction)


class ModifiedTorsionFreeDeclaration(Definition):
    """``ᴸT(∇) = 0`` declared, solved for the bracket in the
    expansion direction:

        [u,v]_E → ∇_u v − ∇_v u + Σ_s L(e^s, ∇_{e_s}u, v).

    The right-hand side contains no bracket, so the rewrite
    terminates; the recombination rule collects a different shape,
    so no ping-pong."""

    anchor = AlgebroidBracket

    def __init__(
        self,
        alg: Algebroid,
        conn: Connection,
        fr: Frame,
        *,
        bound: str = "s",
    ) -> None:
        self._alg = alg
        self._conn = conn
        self._fr = fr
        self._bound = bound
        self.name = (
            f"declared ᴸT-free ({alg.name}, {conn.name}): "
            "[u,v] = ∇_u v − ∇_v u + ΣL(e^s,∇u,v)"
        )

    def matches(self, expr: Expr) -> bool:
        return (
            isinstance(expr, AlgebroidBracket)
            and expr.algebroid_name == self._alg.name
        )

    def rewrite(self, expr: Expr) -> Expr:
        u, v = expr.u, expr.v
        return Sum(
            self._conn(u, v),
            Neg(self._conn(v, u)),
            _locality_sum(
                self._alg, self._conn, self._fr, u, v, self._bound
            ),
        )


