"""
Admissible E-connections (Phase 4.F.1) — the admissible-connections
paper (Dereli-Doğan, J. Geom. Phys. 186 (2023); "ADM" below).

On a local almost-Leibniz algebroid ``(E, ρ, [·,·]_E, L)`` a linear
E-connection ``∇`` is **admissible** [ADM Def 3.4] iff

    [u,v]_E + [v,u]_E = Σ_s L(e^s, ∇_{e_s}u, v)
                       + Σ_s L(e^s, ∇_{e_s}v, u),

i.e. the bracket's symmetric part is generated by ``L`` through
``∇``. An algebroid admitting such a connection is *anti-commutable*
[ADM Def 3.3]. Admissibility is a STRUCTURE-PAIR property (bracket +
connection), so it enters proofs only through the opt-in
:class:`AdmissibilityDeclaration` — the exact analogue of the C2
symmetric-part declaration, in the same collection direction (a
single-bracket swap orientation would re-create the Phase 3.E.2
rewrite cycle).

Mechanical theorems of this pass:

* **[ADM Prop 3.3]** modified-torsion-freeness forces admissibility:
  under the ``ᴸT = 0`` declaration (:class:`
  ModifiedTorsionFreeDeclaration`, which solves ``ᴸT = 0`` for the
  bracket in the expansion direction) the admissibility equation is
  a theorem.
* **[ADM Cor 3.2]** the modified torsion of an admissible connection
  is antisymmetric — proved in symmetric-part form
  ``ᴸT(u,v) + ᴸT(v,u) = 0`` (the difference shape lets the
  collection declaration fire; the two sides separately have no
  common normal form, by design of the collection-only direction).
* **[ADM Prop 3.2, dull part]** the modified bracket
  ``[u,v]^∇ := [u,v]_E − Σ_s L(e^s, ∇_{e_s}u, v)`` satisfies the
  EXACT left-Leibniz rule ``[fu,v]^∇ = f[u,v]^∇ − ρ(v)(f)u`` for ANY
  connection (no declaration): the coframe recombination cancels the
  locality defect. The modified pair ``(E, ρ, [·,·]^∇, L=0)`` is an
  almost-dull algebroid.
"""

